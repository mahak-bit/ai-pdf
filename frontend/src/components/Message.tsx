"use client";

import type { Answer, Source } from "@/lib/api";
import { segmentAnswer, shorten } from "@/lib/citations";
import { AlertIcon, InfoIcon } from "./icons";

export type Turn = {
  id: string;
  question: string;
  state: "pending" | "done" | "error";
  answer?: Answer;
  error?: string;
};

type Props = {
  turn: Turn;
  activeChunk: string | null;
  onOpenSource: (source: Source) => void;
  onRetry: () => void;
};

export function Message({ turn, activeChunk, onOpenSource, onRetry }: Props) {
  return (
    <article className="space-y-4">
      <div className="flex justify-end">
        <p className="max-w-[85%] whitespace-pre-wrap rounded-2xl rounded-br-md border border-line bg-paper px-4 py-2.5">{turn.question}</p>
      </div>
      <div className="max-w-[68ch]">
        {turn.state === "pending" && <Thinking />}
        {turn.state === "error" && (
          <div role="alert" className="flex gap-3 rounded-xl bg-danger-wash px-4 py-3 text-danger">
            <AlertIcon className="mt-0.5 shrink-0" />
            <div>
              <p>{turn.error}</p>
              <button type="button" onClick={onRetry} className="mt-1.5 text-sm font-medium underline underline-offset-2">
                Try again
              </button>
            </div>
          </div>
        )}
        {turn.state === "done" && turn.answer && (
          <AnswerBody answer={turn.answer} activeChunk={activeChunk} onOpenSource={onOpenSource} />
        )}
      </div>
    </article>
  );
}

function Thinking() {
  return (
    <p className="flex items-center gap-2 text-graphite" role="status">
      <span className="flex gap-1" aria-hidden="true">
        {[0, 1, 2].map((i) => (
          <span key={i} className="thinking-dot size-1.5 rounded-full bg-blue" style={{ animationDelay: `${i * 0.15}s` }} />
        ))}
      </span>
      Searching the document…
    </p>
  );
}

function AnswerBody({ answer, activeChunk, onOpenSource }: { answer: Answer; activeChunk: string | null; onOpenSource: (s: Source) => void }) {
  if (answer.status === "abstained") {
    return (
      <div className="flex gap-3 rounded-xl border border-line bg-paper px-4 py-3">
        <InfoIcon className="mt-0.5 shrink-0 text-graphite" />
        <div>
          <p>{answer.answer}</p>
          <p className="mt-1 text-sm text-graphite">DocuMind only answers from what the document says.</p>
        </div>
      </div>
    );
  }

  if (answer.status === "retrieval_only") {
    return (
      <div className="space-y-3">
        <p className="rounded-xl bg-caution-wash px-4 py-3 text-sm text-caution">{answer.answer}</p>
        <SourceList sources={answer.sources} activeChunk={activeChunk} onOpenSource={onOpenSource} />
      </div>
    );
  }

  const segments = segmentAnswer(answer.answer, answer.sources);
  return (
    <div className="space-y-4">
      <p className="whitespace-pre-wrap text-[1.0rem] leading-[1.7]">
        {segments.map((seg, i) =>
          seg.kind === "text" ? (
            <span key={i}>{seg.text}</span>
          ) : (
            <CitationChip key={i} source={seg.source} active={seg.source.chunk_id === activeChunk} onClick={() => onOpenSource(seg.source)} />
          ),
        )}
      </p>
      <SourceList sources={answer.sources} activeChunk={activeChunk} onOpenSource={onOpenSource} />
      {answer.model && <p className="text-xs text-mute">Generated by {answer.model.split(":").slice(1).join(":")} from {answer.retrieved} retrieved passages</p>}
    </div>
  );
}

function CitationChip({ source, active, onClick }: { source: Source; active: boolean; onClick: () => void }) {
  return (
    <button
      type="button"
      onClick={onClick}
      aria-label={`Show source on page ${source.page}`}
      aria-pressed={active}
      className={[
        "mx-0.5 inline-flex translate-y-[-1px] items-center rounded-md px-1.5 py-px align-baseline text-[0.78rem] font-semibold tabular-nums transition-colors",
        active ? "bg-blue text-white" : "bg-wash text-blue-deep hover:bg-blue hover:text-white",
      ].join(" ")}
    >
      p.&nbsp;{source.page}
    </button>
  );
}

function SourceList({ sources, activeChunk, onOpenSource }: { sources: Source[]; activeChunk: string | null; onOpenSource: (s: Source) => void }) {
  if (!sources.length) return null;
  return (
    <div>
      <h3 className="mb-2 text-sm font-medium text-graphite">{sources.length === 1 ? "Source" : `${sources.length} sources`}</h3>
      <ul className="divide-y divide-line overflow-hidden rounded-xl border border-line bg-paper">
        {sources.map((s) => {
          const active = s.chunk_id === activeChunk;
          return (
            <li key={s.chunk_id}>
              <button
                type="button"
                onClick={() => onOpenSource(s)}
                className={`flex w-full gap-4 px-4 py-3 text-left transition-colors ${active ? "bg-wash" : "hover:bg-ivory"}`}
              >
                <span className="w-12 shrink-0 pt-0.5 text-sm font-semibold tabular-nums text-blue-deep">p.&nbsp;{s.page}</span>
                <span className="doc-quote min-w-0 text-graphite">{shorten(s.excerpt, 200)}</span>
              </button>
            </li>
          );
        })}
      </ul>
    </div>
  );
}
